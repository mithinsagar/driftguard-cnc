"""make data: manifest + count verification + data audit + per-window feature cache + split manifests."""
from __future__ import annotations

import json
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from driftguard.data import splits  # noqa: E402
from driftguard.data.dataset import SAMPLE_RATE, build_manifest, load_signal, verify  # noqa: E402
from driftguard.features.dsp import FEATURE_NAMES, features, windows  # noqa: E402

CACHE = Path("data/cache")
FIG = Path("reports/figures")


def _one(path: str):
    sig = load_signal(path)
    f = features(windows(sig))
    stats = {"min": sig.min(0).tolist(), "max": sig.max(0).tolist(), "std": sig.std(0).tolist(), "dtype": "float32"}
    return f, stats


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    df = build_manifest()
    counts = verify(df)
    print("verified", counts)

    with ProcessPoolExecutor() as ex:
        out = list(ex.map(_one, df["path"], chunksize=8))
    feats = [o[0] for o in out]
    df["n_windows"] = [len(f) for f in feats]
    for ax, name in enumerate("xyz"):
        df[f"min_{name}"] = [o[1]["min"][ax] for o in out]
        df[f"max_{name}"] = [o[1]["max"][ax] for o in out]
        df[f"std_{name}"] = [o[1]["std"][ax] for o in out]
    X = np.concatenate(feats)
    file_idx = np.concatenate([np.full(len(f), i, dtype=np.int32) for i, f in enumerate(feats)])
    np.savez_compressed(CACHE / "features.npz", X=X, file_idx=file_idx, names=np.array(FEATURE_NAMES))
    df.to_csv("data/manifest.csv", index=False)
    print("features", X.shape, "files with 0 windows:", int((df.n_windows == 0).sum()))

    folds = splits.all_folds(df)
    for proto in folds.values():
        for fold in proto:
            splits.check_no_leakage(fold)
    splits.save(folds)
    write_audit(df, folds)


def write_audit(df: pd.DataFrame, folds: dict):
    lines = ["# Data audit", "", "Generated by `scripts/prepare.py` from the official repository. Do not edit by hand.", ""]
    lines += ["## Counts", "", f"Files: {len(df)}, good: {(df.label == 'good').sum()}, bad: {(df.label == 'bad').sum()}, "
              f"total duration: {df.seconds.sum() / 3600:.2f} h, windows (1 s, 0.5 s hop): {df.n_windows.sum()}", ""]
    t = pd.crosstab(df.machine, df.label, margins=True)
    lines += ["### By machine", "", t.to_markdown(), ""]
    t = pd.crosstab(df.process, [df.machine, df.label])
    lines += ["### By process and machine", "", t.to_markdown(), ""]
    t = pd.crosstab(df.timeframe + " (" + df.t_order.astype(str) + ")", [df.machine, df.label])
    lines += ["### By timeframe", "", t.sort_index(key=lambda s: s.str[-7:-1]).to_markdown(), ""]
    d = df.groupby("process").seconds.describe()[["count", "mean", "min", "max"]].round(1)
    lines += ["## Recording duration (seconds) by process", "", d.to_markdown(), ""]
    r = df.groupby("machine")[[f"{k}_{a}" for k in ("min", "max", "std") for a in "xyz"]].median().round(1)
    lines += ["## Raw value ranges (median over files)", "",
              "The README does not state physical units, so values are reported as stored.", "", r.to_markdown(), ""]
    lines += ["## Split protocols", ""]
    for proto, fl in folds.items():
        rows = []
        idx = df.set_index("file_id")
        for f in fl:
            te = idx.loc[f["test"]]
            rows.append({"fold": f["name"], "train_good": len(f["train_good"]), "val_good": len(f["val_good"]),
                         "cal_good": len(f["cal_good"]), "val_bad": len(f["val_bad"]),
                         "test_good": int((te.label == "good").sum()), "test_bad": int((te.label == "bad").sum())})
        lines += [f"### {proto}", "", pd.DataFrame(rows).to_markdown(index=False), ""]
    Path("docs").mkdir(exist_ok=True)
    Path("docs/data_audit.md").write_text("\n".join(lines))

    # Figure: bad files per machine x process, and example spectrograms.
    piv = pd.crosstab(df[df.label == "bad"].process, df[df.label == "bad"].machine).reindex(sorted(df.process.unique()), fill_value=0)
    fig, ax = plt.subplots(figsize=(4.2, 5))
    im = ax.imshow(piv.values, cmap="Reds")
    ax.set_xticks(range(piv.shape[1]), piv.columns)
    ax.set_yticks(range(piv.shape[0]), piv.index)
    for (i, j), v in np.ndenumerate(piv.values):
        ax.text(j, i, int(v), ha="center", va="center", fontsize=8)
    ax.set_title("Anomalous recordings per process and machine", fontsize=9)
    fig.colorbar(im, ax=ax, shrink=0.6)
    fig.tight_layout()
    fig.savefig(FIG / "bad_files_heatmap.png", dpi=160)
    plt.close(fig)

    fig, axes = plt.subplots(2, 3, figsize=(10, 4.6), sharey=True)
    for col, op in enumerate(["OP01", "OP07", "OP13"]):
        for row, lab in enumerate(["good", "bad"]):
            sub = df[(df.process == op) & (df.label == lab)]
            ax = axes[row, col]
            if len(sub):
                sig = load_signal(sub.iloc[0].path)[:, 2]
                ax.specgram(sig, NFFT=256, Fs=SAMPLE_RATE, noverlap=128, cmap="magma")
            ax.set_title(f"{op} {lab} (Z axis)", fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "example_spectrograms.png", dpi=140)
    plt.close(fig)
    (Path("data") / "README.md").write_text(json.dumps({
        "source": "https://github.com/boschresearch/CNC_Machining", "licence": "CC-BY-4.0 (data), BSD-3-Clause (loader code)",
        "files": len(df), "good": int((df.label == "good").sum()), "bad": int((df.label == "bad").sum()),
        "manifest_sha256_of_hashes": __import__("hashlib").sha256("".join(df.sha256).encode()).hexdigest(),
    }, indent=1))


if __name__ == "__main__":
    main()
