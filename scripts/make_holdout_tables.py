"""Summarise held-out streaming results (results/holdout/*.json) into docs/holdout_tables.md and results/holdout_summary.json."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

NAMES = {"P0_frozen": "frozen threshold", "P1_naive": "naive self-labelling", "P2_delayed_d5": "delayed-label admission (k=5)",
         "P4_w1acas_default": "IBM W1-ACAS, default settings", "P4_w1acas_tuned": "IBM W1-ACAS, tuned on first half",
         "P5_default_d5": "delayed-label + ACI, default (k=5)", "P5_tuned_d5": "delayed-label + ACI, tuned on first half (k=5)",
         "P5_tuned_d20": "delayed-label + ACI, tuned on first half (k=20)"}


def recall_at_far(g, target):
    g = g.sort_values("far")
    if g.far.isna().all() or target < g.far.min() or target > g.far.max():
        return np.nan
    return float(np.interp(target, g.far, g.recall))


def main():
    rows = []
    for p in sorted(Path("results/holdout").glob("*.json")):
        r = json.loads(p.read_text())
        ev = pd.DataFrame(r["eval"])
        for pol, g in ev.groupby("policy"):
            at5 = g[g.alpha == 0.05].iloc[0]
            rows.append({"protocol": r["protocol"], "scorer": r["scorer"], "seed": r["seed"], "scenario": r["scenario"], "policy": pol,
                         "far_at_alpha5": float(at5.far), "recall_at_alpha5": float(at5.recall), "n_bad_eval": int(at5.n_bad),
                         "recall_at_far_2pct": recall_at_far(g, 0.02), "recall_at_far_5pct": recall_at_far(g, 0.05),
                         "mean_abs_cal_error": float((g.far - g.alpha).abs().mean()), "selected": r["selected"]})
    res = pd.DataFrame(rows)
    Path("results/holdout_summary.json").write_text(json.dumps(res.to_dict(orient="records"), indent=1, default=float))

    def pct(x):
        return "n/a" if x != x else f"{100 * x:.1f}%"

    piv = res.pivot_table(index=["protocol", "scorer", "seed", "scenario"], columns="policy",
                          values=["mean_abs_cal_error", "recall_at_far_2pct", "recall_at_far_5pct"])
    comp = {}
    for rival in ("P4_w1acas_default", "P4_w1acas_tuned"):
        cal = piv["mean_abs_cal_error"]
        comp[rival] = {"settings": int(len(cal)), "calibration_better": int((cal["P5_tuned_d5"] < cal[rival]).sum())}
        for k in ("recall_at_far_2pct", "recall_at_far_5pct"):
            d = piv[k][["P5_tuned_d5", rival]].dropna()
            comp[rival][k] = {"comparable": int(len(d)), "better": int((d["P5_tuned_d5"] > d[rival] + 1e-9).sum()),
                              "worse": int((d["P5_tuned_d5"] < d[rival] - 1e-9).sum()),
                              "mean_diff_points": float(100 * (d["P5_tuned_d5"] - d[rival]).mean()) if len(d) else float("nan")}
    Path("results/holdout_comparison.json").write_text(json.dumps(comp, indent=1))

    out = ["<!-- generated by scripts/make_holdout_tables.py; do not edit -->", "",
           "Hyperparameters of every tunable policy were chosen on the first half of each stream (at α = 5%); every number below is "
           "measured on the second half only. The burst of real faulty runs is placed in the second half.", "",
           "### Proposed policy versus IBM W1-ACAS on held-out halves", "",
           "| Rival | Settings | P5 better calibrated | Recall at matched 2% FAR: better / worse (mean diff) | Recall at matched 5% FAR: better / worse (mean diff) |",
           "|---|---|---|---|---|"]
    for rival, c in comp.items():
        r2, r5 = c["recall_at_far_2pct"], c["recall_at_far_5pct"]
        out.append(f"| {NAMES[rival]} | {c['settings']} | {c['calibration_better']} of {c['settings']} | {r2['better']} / {r2['worse']} of "
                   f"{r2['comparable']} ({r2['mean_diff_points']:+.1f} pts) | {r5['better']} / {r5['worse']} of {r5['comparable']} ({r5['mean_diff_points']:+.1f} pts) |")
    out.append("")
    for (proto, scen), g in res.groupby(["protocol", "scenario"]):
        out += [f"### Held-out halves, protocol `{proto}`, {scen} order", "",
                "| Scorer | Seed | Policy | FAR at α=5% | Recall at α=5% | Recall at matched FAR 2% | Recall at matched FAR 5% | Mean abs. calibration error |",
                "|---|---|---|---|---|---|---|---|"]
        for _, r in g.sort_values(["scorer", "seed", "policy"]).iterrows():
            out.append(f"| {r.scorer} | {r.seed} | {NAMES.get(r.policy, r.policy)} | {pct(r.far_at_alpha5)} | {pct(r.recall_at_alpha5)} | "
                       f"{pct(r.recall_at_far_2pct)} | {pct(r.recall_at_far_5pct)} | {pct(r.mean_abs_cal_error)} |")
        out.append("")
    Path("docs/holdout_tables.md").write_text("\n".join(out) + "\n")
    print(json.dumps(comp, indent=1))


if __name__ == "__main__":
    main()
