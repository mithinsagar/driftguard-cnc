"""Summarise streaming sweeps: recall at matched false-alarm rate and calibration error per policy."""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import beta

POLICY_NAME = {
    "P0_frozen": "frozen threshold", "P1_naive": "naive self-labelling", "P2_delayed_d5": "delayed-label admission (k=5)",
    "P2_delayed_d20": "delayed-label admission (k=20)", "P3_aci": "ACI, delayed errors", "P4_w1acas": "IBM W1-ACAS (label-free)",
    "P5_delayed_aci_d5": "delayed-label + ACI (k=5, proposed)", "P5_delayed_aci_d20": "delayed-label + ACI (k=20)",
}


def recall_at_far(g: pd.DataFrame, target: float) -> float:
    """Linear interpolation of the (FAR, recall) operating curve; nan if target outside the achieved FAR range."""
    g = g.sort_values("far")
    far, rec = g.far.to_numpy(), g.recall.to_numpy()
    if target < far.min() or target > far.max():
        return float("nan")
    return float(np.interp(target, far, rec))


def cp(k, n):
    a = 0.025
    return (0.0 if k == 0 else beta.ppf(a, k, n - k + 1), 1.0 if k == n else beta.ppf(1 - a, k + 1, n - k))


def main():
    rows = []
    for p in sorted(Path("results").glob("stream_sweep_*.json")):
        m = re.match(r"stream_sweep_(\w+?)_(B\d|AE)_seed(\d+)_(burst|natural)(_labelrates)?\.json", p.name)
        if not m:
            continue
        proto, scorer, _, scen, lr = m.groups()
        df = pd.DataFrame(json.loads(p.read_text()))
        for pol, g in df.groupby("policy"):
            at5 = g[g.alpha == 0.05].iloc[0]
            rows.append({"protocol": proto, "scorer": scorer, "scenario": scen, "label_ablation": bool(lr), "policy": pol,
                         "recall_at_far_2pct": recall_at_far(g, 0.02), "recall_at_far_5pct": recall_at_far(g, 0.05),
                         "mean_abs_cal_error": float((g.far - g.alpha).abs().mean()),
                         "far_at_alpha5": float(at5.far), "recall_at_alpha5": float(at5.recall),
                         "recall_at_alpha5_ci": cp(int(at5.detected), int(at5.n_bad)), "n_bad": int(at5.n_bad), "n_good": int(at5.n_good)})
    res = pd.DataFrame(rows)
    Path("results/stream_summary.json").write_text(json.dumps(res.to_dict(orient="records"), indent=1, default=float))

    def pct(x):
        return "n/a" if x != x else f"{100 * x:.1f}%"

    out = ["<!-- generated by scripts/make_stream_tables.py; do not edit -->", ""]
    main_rows = res[~res.label_ablation]
    for (proto, scen), g in main_rows.groupby(["protocol", "scenario"]):
        out += [f"### Streaming, protocol `{proto}`, {scen} order", "",
                "| Scorer | Policy | Achieved FAR at α=5% | Recall at α=5% [95% CI] | Recall at matched FAR 2% | Recall at matched FAR 5% "
                "| Mean abs. calibration error |",
                "|---|---|---|---|---|---|---|"]
        for _, r in g.sort_values(["scorer", "policy"]).iterrows():
            ci = r.recall_at_alpha5_ci
            out.append(f"| {r.scorer} | {POLICY_NAME.get(r.policy, r.policy)} | {pct(r.far_at_alpha5)} | {pct(r.recall_at_alpha5)} "
                       f"[{pct(ci[0])}, {pct(ci[1])}] | {pct(r.recall_at_far_2pct)} | {pct(r.recall_at_far_5pct)} | {pct(r.mean_abs_cal_error)} |")
        out.append("")
    lab = res[res.label_ablation]
    if not lab.empty:
        out += ["### Label coverage ablation (lomo, burst, supervised scorer)", "",
                "| Policy | Achieved FAR at α=5% | Recall at α=5% | Recall at matched FAR 5% | Mean abs. calibration error |", "|---|---|---|---|---|"]
        for _, r in lab.sort_values("policy").iterrows():
            out.append(f"| {r.policy} | {pct(r.far_at_alpha5)} | {pct(r.recall_at_alpha5)} | {pct(r.recall_at_far_5pct)} | {pct(r.mean_abs_cal_error)} |")
    Path("docs/stream_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
